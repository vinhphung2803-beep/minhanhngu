"""Build a 1-bit bitmap font atlas (assets/ui/font.png + js/fontdata.js) from DejaVu Sans.
Includes ASCII + Vietnamese letters so the personal letter can be written in Vietnamese."""
from PIL import Image, ImageDraw, ImageFont
import os, json
ROOT = os.path.join(os.path.dirname(__file__), '..')
FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
SIZE = 9
VI = 'ÀÁẢÃẠĂẰẮẲẴẶÂẦẤẨẪẬÈÉẺẼẸÊỀẾỂỄỆÌÍỈĨỊÒÓỎÕỌÔỒỐỔỖỘƠỜỚỞỠỢÙÚỦŨỤƯỪỨỬỮỰỲÝỶỸỴĐ'
chars = [chr(c) for c in range(32, 127)] + list(VI) + list(VI.lower()) + list('’‘“”…♥★')
f = ImageFont.truetype(FONT, SIZE)
CW, CH = 10, 14          # cell size in atlas
COLS = 32
rows = (len(chars) + COLS - 1) // COLS
atlas = Image.new('RGBA', (CW * COLS, CH * rows), (0, 0, 0, 0))
widths = {}
for i, ch in enumerate(chars):
    im = Image.new('L', (CW, CH), 0); d = ImageDraw.Draw(im); d.fontmode = '1'
    d.text((0, 3), ch, font=f, fill=255)
    adv = int(round(f.getlength(ch)))
    # actual ink width
    bb = im.getbbox(); ink = bb[2] if bb else 0
    widths[ch] = max(adv, ink) if ch != ' ' else 3
    px = im.load(); a = atlas.load(); ox, oy = (i % COLS) * CW, (i // COLS) * CH
    for y in range(CH):
        for x in range(CW):
            if px[x, y] > 127: a[ox + x, oy + y] = (255, 255, 255, 255)
os.makedirs(os.path.join(ROOT, 'assets', 'ui'), exist_ok=True)
atlas.save(os.path.join(ROOT, 'assets', 'ui', 'font.png'))
with open(os.path.join(ROOT, 'js', 'fontdata.js'), 'w', encoding='utf-8') as fh:
    fh.write('// AUTO-GENERATED by tools/make_font.py - do not edit by hand\n')
    fh.write('const FONT_DATA = ' + json.dumps({'cw': CW, 'ch': CH, 'cols': COLS, 'chars': ''.join(chars), 'widths': [widths[c] for c in chars]}, ensure_ascii=False) + ';\n')
print('font ok', len(chars), atlas.size)
